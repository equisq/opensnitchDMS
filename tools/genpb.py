#!/usr/bin/env python3
"""Generates backend/protocol/ui.pb.go from ui.proto.

Dev-time only (needs `pip install grpcio-tools`). It emits plain structs with
protobuf struct tags, which the protobuf-go runtime reads natively, so the build
needs nothing but google.golang.org/protobuf and grpc -- no protoc plugins.
Re-run it only if ui.proto changes.
"""
import os, subprocess, sys, tempfile
from google.protobuf import descriptor_pb2 as d

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "backend", "protocol", "ui.pb.go")
with tempfile.NamedTemporaryFile(suffix=".pb") as t:
    subprocess.check_call([sys.executable, "-m", "grpc_tools.protoc", f"-I{here}",
                           f"--descriptor_set_out={t.name}", "ui.proto"])
    fds = d.FileDescriptorSet.FromString(open(t.name, "rb").read())
f = fds.file[0]
F = d.FieldDescriptorProto

def camel(s):
    r, up = "", True
    for c in s:
        if c == "_":
            up = True
        elif up:
            r += c.upper(); up = False
        else:
            r += c
    return r

def json_name(s):
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])

SCALAR = {F.TYPE_STRING: ("string", "bytes"), F.TYPE_BOOL: ("bool", "varint"),
          F.TYPE_UINT64: ("uint64", "varint"), F.TYPE_INT64: ("int64", "varint"),
          F.TYPE_UINT32: ("uint32", "varint"), F.TYPE_INT32: ("int32", "varint")}

def gotype(fld, parent):
    """(go type, wire word, extra tag)"""
    if fld.type == F.TYPE_MESSAGE:
        return "*" + goname(fld.type_name), "bytes", ""
    if fld.type == F.TYPE_ENUM:
        n = goname(fld.type_name)
        return n, "varint", ",enum=" + fld.type_name.lstrip(".")
    g, w = SCALAR[fld.type]
    return g, w, ""

def goname(full):
    # ".protocol.Alert.Priority" -> Alert_Priority
    return "_".join(full.lstrip(".").split(".")[1:])

w = []
P = w.append
P("// Code generated by tools/genpb.py from ui.proto. DO NOT EDIT.\n")
P("package protocol\n")
P('import (\n\t"google.golang.org/protobuf/runtime/protoimpl"\n)\n')

def emit_enum(name, e):
    P(f"type {name} int32\n")
    P("const (")
    for v in e.value:
        pre = name if "_" not in name or True else name
        P(f"\t{name}_{v.name} {name} = {v.number}")
    P(")\n")
    P(f"var {name}_name = map[int32]string{{")
    for v in e.value:
        P(f'\t{v.number}: "{v.name}",')
    P("}\n")
    P(f"func (x {name}) String() string {{ if s, ok := {name}_name[int32(x)]; ok {{ return s }}; return \"UNKNOWN\" }}\n")

for e in f.enum_type:
    emit_enum(e.name, e)

def emit_msg(m, prefix=""):
    name = prefix + m.name
    full = ".protocol." + name.replace("_", ".")
    for e in m.enum_type:
        emit_enum(name + "_" + e.name, e)
    nested = {"." + "protocol" + "." + name.replace("_", ".") + "." + n.name: n for n in m.nested_type}
    oneofs = {}
    P(f"type {name} struct {{")
    for fld in m.field:
        gname = camel(fld.name)
        jn = json_name(fld.name)
        jpart = f",json={jn}" if jn != fld.name else ""
        if fld.type_name in nested and nested[fld.type_name].options.map_entry:
            me = nested[fld.type_name]
            k, v = me.field[0], me.field[1]
            kg, kw, _ = gotype(k, m); vg, vw, vx = gotype(v, m)
            P(f'\t{gname} map[{kg}]{vg} `protobuf:"bytes,{fld.number},rep,name={fld.name}{jpart},proto3" protobuf_key:"{kw},1,opt,name=key,proto3" protobuf_val:"{vw},2,opt,name=value,proto3{vx}"`')
            continue
        g, wire, extra = gotype(fld, m)
        if fld.HasField("oneof_index"):
            oneofs.setdefault(fld.oneof_index, []).append((fld, gname, g, wire, extra, jpart))
            continue
        if fld.label == F.LABEL_REPEATED:
            packed = ",packed" if wire == "varint" else ""
            P(f'\t{gname} []{g} `protobuf:"{wire},{fld.number},rep{packed},name={fld.name}{jpart},proto3{extra}"`')
        else:
            P(f'\t{gname} {g} `protobuf:"{wire},{fld.number},opt,name={fld.name}{jpart},proto3{extra}"`')
        if False: pass
    for idx, items in sorted(oneofs.items()):
        on = m.oneof_decl[idx].name
        P(f'\t{camel(on)} is{name}_{camel(on)} `protobuf_oneof:"{on}"`')
    P("}\n")
    P(f"func (x *{name}) Reset()         {{ *x = {name}{{}} }}")
    P(f"func (x *{name}) String() string {{ return protoimpl.X.MessageStringOf(protoimpl.X.ProtoMessageV2Of(x)) }}")
    P(f"func (*{name}) ProtoMessage()    {{}}")
    P(f'func (*{name}) XXX_MessageName() string {{ return "protocol.{name.replace("_", ".")}" }}\n')
    for fld in m.field:
        if fld.type_name in nested and nested[fld.type_name].options.map_entry:
            continue
        if fld.HasField("oneof_index"):
            continue
        gname = camel(fld.name)
        g, _, _ = gotype(fld, m)
        if fld.label == F.LABEL_REPEATED:
            g = "[]" + g
        z = {"string": '""', "bool": "false"}.get(g, "nil" if g.startswith(("*", "[]")) else "0")
        P(f"func (x *{name}) Get{gname}() {g} {{ if x != nil {{ return x.{gname} }}; return {z if not (g in ('uint64','uint32','int64','int32') ) else '0'} }}")
    P("")
    for idx, items in sorted(oneofs.items()):
        on = camel(m.oneof_decl[idx].name)
        P(f"type is{name}_{on} interface {{ is{name}_{on}() }}\n")
        wr = []
        for fld, gname, g, wire, extra, jpart in items:
            wn = f"{name}_{gname}"
            wr.append(wn)
            P(f'type {wn} struct {{ {gname} {g} `protobuf:"{wire},{fld.number},opt,name={fld.name}{jpart},proto3,oneof{extra}"` }}')
            P(f"func (*{wn}) is{name}_{on}() {{}}")
            z = "nil" if g.startswith("*") else '""'
            P(f"func (x *{name}) Get{gname}() {g} {{ if v, ok := x.Get{on}().(*{wn}); ok {{ return v.{gname} }}; return {z} }}")
        P(f"func (x *{name}) Get{on}() is{name}_{on} {{ if x != nil {{ return x.{on} }}; return nil }}")
        P(f"func (*{name}) XXX_OneofWrappers() []interface{{}} {{ return []interface{{}}{{" + ", ".join(f"(*{n})(nil)" for n in wr) + "} }\n")
    for n in m.nested_type:
        if not n.options.map_entry:
            emit_msg(n, name + "_")

for m in f.message_type:
    emit_msg(m)

open(out, "w").write("\n".join(w) + "\n")
print("wrote", out)
